void WaveGen::_dmaBuildImage() {
    uint32_t N = _plan.N;
    uint8_t cmd = (uint8_t)(0x40 | (((uint8_t)_channel) << 1));   // MULTI_IR write, UDAC = 0: immediate
    for (uint32_t i = 0; i < N; i++) {
        uint16_t v = _waveform_table[i] & 0x0FFF;   // VREF_VDD, PD normal, GAIN_1X: top nibble 0 (setChannelValue's defaults)
        _image[3 * i + 0] = cmd;
        _image[3 * i + 1] = (uint16_t)(v >> 8);
        _image[3 * i + 2] = (uint16_t)((v & 0xFF) | WG_DC_STOP);
        s_addrRing[i] = (uint32_t)&_image[3 * i];
    }
}

static inline uint32_t wgLog2(uint32_t v) { uint32_t r = 0; while ((1u << (r + 1)) <= v) r++; return r; }

// Abort a set of channels the way the datasheet says (12.6.8.3, RP2350-E5):
// clear EN and CHAIN_TO on all of them first (so a chain cannot re-trigger
// one while another is being aborted - B1 and B2 trigger each other), then
// one CHAN_ABORT write for the whole set, then poll. Every wait is bounded:
// this runs on core 0 inside an API call, and the SDK's dma_channel_abort()
// spins unbounded on BUSY - which is exactly where a channel parked on a
// pacing timer that has just been stopped can leave it. Returns false if a
// channel would not go quiet in time (counted by the caller).
static bool wgAbortChannels(uint32_t mask) {
    for (uint ch = 0; ch < NUM_DMA_CHANNELS; ch++) {
        if (!(mask & (1u << ch))) continue;
        hw_write_masked(&dma_hw->ch[ch].al1_ctrl,
                        (ch << DMA_CH0_CTRL_TRIG_CHAIN_TO_LSB) | (0u << DMA_CH0_CTRL_TRIG_EN_LSB),
                        DMA_CH0_CTRL_TRIG_CHAIN_TO_BITS | DMA_CH0_CTRL_TRIG_EN_BITS);
    }
    dma_hw->abort = mask;
    uint32_t t0 = time_us_32();
    while ((dma_hw->abort & mask) && (time_us_32() - t0) < 2000) { tight_loop_contents(); }
    bool ok = (dma_hw->abort & mask) == 0;
    for (uint ch = 0; ch < NUM_DMA_CHANNELS; ch++) {
        if (!(mask & (1u << ch))) continue;
        uint32_t t1 = time_us_32();
        while ((dma_hw->ch[ch].ctrl_trig & DMA_CH0_CTRL_TRIG_BUSY_BITS) && (time_us_32() - t1) < 2000) { tight_loop_contents(); }
        if (dma_hw->ch[ch].ctrl_trig & DMA_CH0_CTRL_TRIG_BUSY_BITS) ok = false;
    }
    return ok;
}

bool WaveGen::_dmaStart() {
    if (!_dmaAvailable || !_initialized || _waveform_table == nullptr) return false;
    if (_dmaStreaming) return true;

    DmaPlan p = _planRate(_frequency_hz);
    if (!p.ok) return false;
    _plan = p;
    _table_size = p.N;
    _buildWaveformTable();
    _dmaBuildImage();

    i2c_hw_t* hw = i2c0_hw;
    // The bus must be idle. Wire's transactions are blocking and every user
    // is core 0 (this core), so it is - bounded wait anyway.
    uint32_t t0 = time_us_32();
    while ((hw->status & I2C_IC_STATUS_ACTIVITY_BITS) && (time_us_32() - t0) < 3000) { tight_loop_contents(); }
    if (hw->status & I2C_IC_STATUS_ACTIVITY_BITS) return false;

    // Target = the DAC (TAR can only change while the block is disabled -
    // Wire does the same dance per transaction, and re-does it on its next).
    hw->enable = 0;
    hw->tar = _dac.getAddress();
    hw->enable = 1;
    (void)hw->clr_tx_abrt;
    hw->dma_tdlr = 8;                                   // DREQ while <= 8 of 16 entries queued
    hw->dma_cr = I2C_IC_DMA_CR_TDMAE_BITS;

    // A: image -> TX FIFO, 3 entries per trigger, paced by the FIFO
    dma_channel_config ca = dma_channel_get_default_config((uint)_chA);
    channel_config_set_transfer_data_size(&ca, DMA_SIZE_16);
    channel_config_set_read_increment(&ca, true);
    channel_config_set_write_increment(&ca, false);
    channel_config_set_dreq(&ca, i2c_get_dreq(i2c0, true));
    dma_channel_configure((uint)_chA, &ca, &hw->data_cmd, _image, 3, false);

    // B2: address ring -> A's READ_ADDR_TRIG (one write = one sample), then B1
    dma_channel_config cb2 = dma_channel_get_default_config((uint)_chB2);
    channel_config_set_transfer_data_size(&cb2, DMA_SIZE_32);
    channel_config_set_read_increment(&cb2, true);
    channel_config_set_write_increment(&cb2, false);
    channel_config_set_ring(&cb2, false, wgLog2(4u * p.N));
    channel_config_set_chain_to(&cb2, (uint)_chB1);
    dma_channel_configure((uint)_chB2, &cb2, &dma_hw->ch[_chA].al3_read_addr_trig, s_addrRing, 1, false);

    // B1: the divider - D timer ticks per pass, then B2
    dma_channel_config cb1 = dma_channel_get_default_config((uint)_chB1);
    channel_config_set_transfer_data_size(&cb1, DMA_SIZE_32);
    channel_config_set_read_increment(&cb1, false);
    channel_config_set_write_increment(&cb1, false);
    channel_config_set_dreq(&cb1, dma_get_timer_dreq((uint)_dmaTimer));
    channel_config_set_chain_to(&cb1, (uint)_chB2);
    dma_channel_configure((uint)_chB1, &cb1, &_dummyDst, &_dummySrc, p.D, false);

    _lastRingAddr = (uint32_t)s_addrRing;
    _lastProgressUs = time_us_32();
    _dmaWedged = false;
    _laps = 0;
    _actual_frequency = p.actualHz;
    __dmb();
    dma_channel_start((uint)_chB1);                      // armed, no ticks yet
    dma_timer_set_fraction((uint)_dmaTimer, p.X, p.Y);  // pacing begins
    _dmaStreaming = true;
    _dmaStarts++;
    return true;
}

void WaveGen::_dmaStop() {
    if (!_dmaStreaming) return;
    i2c_hw_t* hw = i2c0_hw;
    uint32_t t0 = time_us_32();
    spin_lock_t* lk = (_lockId >= 0) ? spin_lock_instance((uint)_lockId) : nullptr;
    uint32_t save = lk ? spin_lock_blocking(lk) : 0;

    // 1. Take the pacing pair down: EN + chain off on both, one abort for
    //    both, then the timer to 0. (Not the timer first: a channel parked on
    //    a stopped DREQ is the case the abort spins on - see wgAbortChannels.)
    if (!wgAbortChannels((1u << _chB1) | (1u << _chB2))) _abortTimeouts++;
    dma_timer_set_fraction((uint)_dmaTimer, 0, 1);

    // 2. A only ever pushes whole 3-entry bursts: let the in-flight one finish
    //    (microseconds), so the FIFO ends on a STOP entry.
    uint32_t tA = time_us_32();
    while (dma_channel_is_busy((uint)_chA) && (time_us_32() - tA) < 2000) { tight_loop_contents(); }
    if (dma_channel_is_busy((uint)_chA)) {
        // Wedged: the FIFO is full and not draining (bus stuck). Abort A and
        // complete the sample by hand so the transaction still ends with a
        // STOP - then the block's own abort if even that does not drain.
        uint32_t remaining = dma_channel_hw_addr((uint)_chA)->transfer_count & 0x0FFFFFFFu;
        uint32_t next = dma_channel_hw_addr((uint)_chA)->read_addr;
        if (!wgAbortChannels(1u << _chA)) _abortTimeouts++;
        _wedgeRecoveries++;
        if (remaining > 0 && remaining < 3) {
            const uint16_t* e = (const uint16_t*)next;
            for (uint32_t i = 0; i < remaining; i++) {
                uint32_t tw = time_us_32();
                while (!(hw->status & I2C_IC_STATUS_TFNF_BITS) && (time_us_32() - tw) < 1000) { tight_loop_contents(); }
                if (hw->status & I2C_IC_STATUS_TFNF_BITS) hw->data_cmd = e[i];
            }
        }
    }

    // 3. Drain: FIFO empty and the controller idle.
    uint32_t tD = time_us_32();
    while ((!(hw->status & I2C_IC_STATUS_TFE_BITS) || (hw->status & I2C_IC_STATUS_MST_ACTIVITY_BITS)) &&
           (time_us_32() - tD) < 5000) { tight_loop_contents(); }
    if (!(hw->status & I2C_IC_STATUS_TFE_BITS) || (hw->status & I2C_IC_STATUS_MST_ACTIVITY_BITS)) {
        // The block's own abort: issues a STOP and flushes the TX FIFO.
        hw->enable |= I2C_IC_ENABLE_ABORT_BITS;
        uint32_t tb = time_us_32();
        while ((hw->enable & I2C_IC_ENABLE_ABORT_BITS) && (time_us_32() - tb) < 2000) { tight_loop_contents(); }
        _wedgeRecoveries++;
    }
    hw->dma_cr = 0;
    (void)hw->clr_tx_abrt;

    // The MCP4728 shadow no longer knows this channel's register.
    MCP4728::invalidateCache((int)_channel);

    uint32_t dt = time_us_32() - t0;
    if (dt > _stopWaitMaxUs) _stopWaitMaxUs = dt;
    _dmaStreaming = false;
    _busPaused = false;
    _dmaStops++;
    if (lk) spin_unlock(lk, save);
}

void WaveGen::_dmaRestartIfRunning() {
    if (!_dmaAvailable || !_running) return;
    // isRunning() stays true throughout: the bus gates hold.
    if (_dmaStreaming) _dmaStop();
    _dmaRestarts++;
    _dmaStart();
}

// Core 1, every core2stuff pass while running: progress / wedge / TX_ABRT.
extern "C" void i2c0ArbiterForceRelease(void);
void WaveGen::_dmaMonitor() {
    if (!_dmaStreaming) return;
    uint32_t now = time_us_32();
    // A pause the arbiter held for a repeated-START pair whose second half
    // never came (a Wire error path): release it - the stream must not stay
    // paused forever.
    if (_busPaused && (now - _busPauseStartUs) > 100000) {
        i2c0ArbiterForceRelease();
        busResume();
        _busForcedResumes++;
    }
    uint32_t ra = dma_hw->ch[_chB2].read_addr;
    if (ra != _lastRingAddr) {
        if (ra < _lastRingAddr) {   // the ring wrapped: one full cycle
            _laps++;
            _successful_writes += _plan.N;
        }
        _lastRingAddr = ra;
        _lastProgressUs = now;
    } else if (!_dmaWedged && !_busPaused) {
        // Expected time between samples; "no progress" is only a wedge if
        // several samples should have gone by (a 0.0001 Hz wave at N = 2
        // legitimately sits still for 5000 s).
        float period_us = (_plan.tickHz > 0.0f) ? (1.0e6f / _plan.tickHz) : 1.0e6f;
        uint32_t limit = (uint32_t)(period_us * 4.0f);
        if (limit < 200000) limit = 200000;
        if (limit > 4000000000u) limit = 4000000000u;
        if ((now - _lastProgressUs) > limit) {
            _dmaWedged = true;
            dma_timer_set_fraction((uint)_dmaTimer, 0, 1);   // stop feeding a stuck bus; stop() recovers
        }
    }
    // A NAK (or any abort) flushes the TX FIFO and holds it until cleared;
    // clear it here so the stream heals, count it as failed samples.
    if (i2c0_hw->raw_intr_stat & I2C_IC_RAW_INTR_STAT_TX_ABRT_BITS) {
        _txAborts++;
        _failed_writes++;
        (void)i2c0_hw->clr_tx_abrt;
    }
}


/*!
 *  @file waveGen.cpp
 *
 *   Waveform Generator using MCP4728
 *
 *  T3.3 (C14 in CodeDocs/SCHEDULER_AND_HARDWARE_OFFLOAD.md): the stream is
 *  hardware-owned. What used to be a per-sample loop on core 1 (one Wire
 *  transaction per sample, ~50 us each, core 1 captured for the whole stream,
 *  no LED frames and no crossbar sends meanwhile) is now:
 *
 *    - an IMAGE in RAM: for every one of the N samples of a cycle the exact
 *      three IC_DATA_CMD entries the MCP4728 write used to put on the wire
 *      ([0x40 | ch<<1] [D11..D8] [D7..D0 | STOP]) - a 3-entry burst per
 *      sample, START and STOP generated by the I2C block itself, so every
 *      sample is its own short transaction exactly as before;
 *    - channel A: image -> I2C0 TX FIFO, DREQ = the FIFO, 3 entries per
 *      trigger, read address supplied per burst;
 *    - channel B2: an ADDRESS RING (one word per sample = the address of its
 *      3 entries, read with a hardware ring wrap - which is why N is a power
 *      of two: the ring's 4N bytes must be a power of two, the image's 6N
 *      cannot be) -> A's READ_ADDR_TRIG. One write = one sample burst;
 *    - channel B1: the PACING DIVIDER: D dummy transfers per pass, DREQ = a
 *      DMA pacing timer (clk_sys * X / Y), chained to B2, and B2 chains back
 *      to B1. So one sample every D timer ticks, forever, until the timer is
 *      set to 0. The divider is what reaches below the timer's ~2.3 kHz floor
 *      (0.0001 Hz needs a tick every 5000 s at N = 2).
 *
 *  Frequency = clk_sys * X / (Y * D * N), EXACT to the timer's fraction (the
 *  planner picks N as the largest power of two the bus can carry at that
 *  rate, then D and the best X/Y <= 65535 for the tick); the old model's
 *  "actual frequency" (a 4.67-bytes-per-sample estimate of what the CPU loop
 *  achieved) is gone with the loop. The trade: N is a power of two, so an
 *  unlucky frequency gets up to 2x fewer samples per cycle than the old
 *  arbitrary-N table - in exchange for the frequency being right.
 *
 *  Control (start / stop / re-plan on a setter) is done SYNCHRONOUSLY on
 *  the caller's core, and every caller is core 0 (the MicroPython API - the
 *  VM runs on core 0 - and the menus); I2C0's other users (INA219s, DAC
 *  setters, the OLED on this rev) are core 0 too and already skip while
 *  isRunning() - those gates are BUS gates and stay. Core 1's service() is
 *  a monitor: progress (ring laps), TX_ABRT (counted and cleared - the
 *  block flushes its FIFO on a NAK and holds it until cleared), and a wedge
 *  latch. isRunning() stays true across a setter-triggered restart so no
 *  bus user slips in during the teardown/rebuild.
 *
 *  Stop: the timer goes to 0 (no more ticks), B1/B2 are aborted, A is left
 *  to finish its in-flight burst (it only ever pushes whole 3-entry bursts,
 *  so the FIFO always ends on a STOP entry), then wait for the FIFO to drain
 *  and the bus to go idle, DMA_CR off. A wedged A (bus stuck mid-burst) is
 *  the one path that aborts A and pushes the sample's remaining entries by
 *  hand so the transaction ends with a STOP; then the block's own ABORT.
 *
 *  Sustained overrun is the one structural weakness: if the tick rate
 *  exceeded what the bus can carry, the FIFO would back up, A would stall
 *  mid-burst and B2's next READ_ADDR_TRIG would land on a busy A. The
 *  planner caps the tick at 85 % of the bus capacity computed from I2C0's
 *  actual SCL counts (40 bit-times per sample), so it cannot happen at any
 *  legal setting; the monitor's progress check is the backstop.
 *
 *  Fallback: if a DMA channel or timer cannot be claimed (or Wire is not
 *  I2C0), the legacy per-sample CPU loop below runs exactly as before, and
 *  X says so.
 */


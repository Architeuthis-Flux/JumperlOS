/*!
 *    @brief  Start waveform generation
 */
bool WaveGen::start() {
    if (!_initialized) {
        return false;
    }

    // The bus gate first: from here every other I2C0 user skips.
    _running = true;
    _last_sample_time = micros();
    _sample_count = 0;
    _table_index = 0;
    _use_fallback = false;
    _stats_window_start_us = micros();
    _samples_since_stats = 0;
    _indices_since_stats = 0;
    _repeat_factor = 1;
    _repeat_remaining = _repeat_factor;

    _params_changed = false;

    if (_dmaAvailable) {
        if (_dmaStart()) {
            return true;
        }
        // Could not arm the stream (the bus never went idle, or the planner
        // refused): do NOT stay "running" - that would hold the bus gate with
        // nothing streaming. Loud failure instead.
        _running = false;
        return false;
    }
    _updateTableSize();
    _buildWaveformTable();
    return true;
}

/*!
 *    @brief  Stop waveform generation
 */
void WaveGen::stop() {
    if (_dmaStreaming) {
        _dmaStop();          // with _running still true: the bus is ours until the drain is done
    }
    _running = false;

    // The wave streamed raw MCP4728 codes with globalState.power untouched.
    // If the channel was DAC0 (the default - and the probe feed), the feed's
    // skip-if-parked guard would trust the stale in-window state and leave
    // the buffer at the last sample forever; the bump forces a re-park on
    // the next rebuild.
    extern void infraDacParkEpochBump(void);
    infraDacParkEpochBump();
}

/*!
 *    @brief  Service function - call frequently from main loop (core 1)
 */
void WaveGen::service() {
    if (!_running || !_initialized || _waveform_table == nullptr) {
        return;
    }
    if (_dmaAvailable) {
        _dmaMonitor();
        return;
    }
    _serviceLegacy();
}

// ===========================================================================
// The legacy per-sample loop (fallback only): unchanged.
// ===========================================================================
void WaveGen::_serviceLegacy() {
    // BLOCKING streaming loop for core2: keep the I2C transaction open and
    // write samples continuously. Only exit when stopped or params change.

    // If params changed, rebuild tables and restart streaming
    if (_params_changed) {
        _updateTableSize();
        _buildWaveformTable();
        _updateSampleInterval();
        _params_changed = false;
    }

    uint32_t t0_overall = micros();
    uint32_t samples_sent_this_call = 0;

    // Determine if we should use non-blocking mode (low frequency)
    bool use_nonblocking = (_frequency_hz < WAVEGEN_NONBLOCKING_THRESHOLD_HZ);
    uint32_t samples_to_send = use_nonblocking ? _table_size : UINT32_MAX; // One cycle for low freq, continuous for high freq

    // Per-sample repeated-START streaming to keep bus flow continuous and avoid
    // long buffered drains. Each sample is its own short transaction.

    while (_running && !_params_changed && samples_sent_this_call < samples_to_send) {
        // Would-be watchdog kick from the core-1 stream loop (measure-only
        // stage, KickGap.h): a >= 1 kHz stream holds core 1 here for its whole
        // duration - the site the T1.6 numbers said an enable needs.
        kickGapStamp( 1, KICK_WAVEGEN );
        // Synchronous per-sample write with STOP; simpler and accurate timing
        bool ok = _dac.setChannelValue((MCP4728_channel_t)_channel,
                                       _waveform_table[_table_index]);
        if (!ok) {
            _failed_writes++;
            continue;
        }
        _successful_writes++;

        // Advance to next table entry honoring repeat factor for very low frequencies
        if (_repeat_remaining > 1) {
            _repeat_remaining--;
        } else {
            _repeat_remaining = _repeat_factor;
            _table_index = (_table_index + 1) % _table_size;
            _indices_since_stats++;
        }
        samples_sent_this_call++;
        _samples_since_stats++;
        // Update rolling actual frequency every ~10ms for stability
        uint32_t t_now = micros();
        uint32_t dt = t_now - _stats_window_start_us;
        if (dt >= 10000 && _table_size > 0) { // 10 ms window
            float indices_per_sec = ((float)_indices_since_stats) * (1000000.0f / (float)dt);
            _actual_frequency = indices_per_sec / (float)_table_size;
            _stats_window_start_us = t_now;
            _samples_since_stats = 0;
            _indices_since_stats = 0;
        }
    }

    // Periodic frequency estimate
    uint32_t now = micros();
    (void)t0_overall;
    if (now - _last_stats_time >= 1000000) {
        _updateStatistics();
        _last_stats_time = now;
    }
}


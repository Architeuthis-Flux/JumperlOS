/*!
 *    @brief  Destructor - free buffers if allocated
 */
WaveGen::~WaveGen() {
    if (_waveform_table_allocated && _waveform_table != nullptr) {
        delete[] _waveform_table;
        _waveform_table = nullptr;
        _waveform_table_allocated = false;
    }
    if (_imageAllocated && _image != nullptr) {
        delete[] _image;
        _image = nullptr;
        _imageAllocated = false;
    }
}

/*!
 *    @brief  Initialize the waveform generator
 */
bool WaveGen::begin(uint8_t i2c_address, TwoWire *wire) {
    // The API calls begin() on every wavegen_start(); if a stream is live,
    // release the bus first (isRunning() stays true - the bus is still ours),
    // _dac.begin() below talks to the chip, and start() re-arms.
    if (_dmaStreaming) {
        _dmaStop();
    }
    if (!_dac.begin(i2c_address, wire)) {
        return false;
    }

    // Allocate waveform table buffer
    if (!_waveform_table_allocated) {
        _waveform_table = new (std::nothrow) uint16_t[MAX_WAVEFORM_TABLE_SIZE];
        if (_waveform_table == nullptr) {
            Serial.println("WaveGen: Failed to allocate waveform table");
            return false;
        }
        _waveform_table_allocated = true;
        memset((void*)_waveform_table, 0, MAX_WAVEFORM_TABLE_SIZE * sizeof(uint16_t));
    }

    _dmaClaim();   // once; sets _dmaAvailable or a fallback reason

    _initialized = true;
    _updateTableSize();
    _buildWaveformTable();
    _updateSampleInterval();

    return true;
}

/*!
 *    @brief  End the waveform generator
 */
void WaveGen::end() {
    stop();
    _dac.end();
    _initialized = false;

    // Free allocated buffers (the DMA channels/timer stay claimed - begin()
    // is called on every wavegen_start(), and re-claiming would leak them)
    if (_waveform_table_allocated && _waveform_table != nullptr) {
        delete[] _waveform_table;
        _waveform_table = nullptr;
        _waveform_table_allocated = false;
    }
}


// Best rational X/Y <= maxQ for x in (0, 1] (continued fractions, with the
// last semiconvergent that still fits): the pacing timer runs at
// clk_sys * X / Y, so this is the tick's precision.
static void wgBestFraction(double x, uint32_t maxQ, uint16_t* numOut, uint16_t* denOut) {
    if (x >= 1.0) { *numOut = 1; *denOut = 1; return; }
    if (x <= 0.0) { *numOut = 0; *denOut = 1; return; }
    uint32_t bestP = 1, bestQ = (uint32_t)maxQ;
    double bestErr = fabs(x - (double)bestP / (double)bestQ);
    auto consider = [&](uint32_t p, uint32_t q) {
        if (q == 0 || q > maxQ || p == 0 || p > maxQ) return;
        double e = fabs(x - (double)p / (double)q);
        if (e < bestErr) { bestErr = e; bestP = p; bestQ = q; }
    };
    uint32_t p0 = 0, q0 = 1, p1 = 1, q1 = 0;
    double v = x;
    for (int i = 0; i < 40; i++) {
        double af = floor(v);
        if (af > 4.0e9) break;
        uint32_t a = (uint32_t)af;
        // overflow-safe next convergent
        uint64_t p2 = (uint64_t)a * p1 + p0;
        uint64_t q2 = (uint64_t)a * q1 + q0;
        if (q2 > maxQ) {
            // the largest semiconvergent that still fits
            if (q1 > 0) {
                uint32_t k = (maxQ - q0) / q1;
                if (k >= 1) consider(p0 + k * p1, q0 + k * q1);
            }
            break;
        }
        consider((uint32_t)p2, (uint32_t)q2);
        p0 = p1; q0 = q1; p1 = (uint32_t)p2; q1 = (uint32_t)q2;
        double frac = v - af;
        if (frac < 1e-15) break;
        v = 1.0 / frac;
        if (bestErr == 0.0) break;
    }
    *numOut = (uint16_t)bestP;
    *denOut = (uint16_t)bestQ;
}

// Samples per second the I2C0 bus carries: SCL rate from the block's own
// counts (what Wire programmed - 1 MHz since T1.9), 40 bit-times per sample.
float WaveGen::_busCapacityHz() const {
    i2c_hw_t* hw = i2c0_hw;
    uint32_t speed = (hw->con >> 1) & 0x3;   // IC_CON.SPEED: 1 = standard, 2 = fast, 3 = high
    uint32_t hcnt = (speed == 1) ? hw->ss_scl_hcnt : hw->fs_scl_hcnt;
    uint32_t lcnt = (speed == 1) ? hw->ss_scl_lcnt : hw->fs_scl_lcnt;
    uint32_t period = hcnt + lcnt + 8;       // + spike filter / edge margins
    if (period < 20) period = 20;
    float scl = (float)clock_get_hz(clk_sys) / (float)period;
    if (scl > 3.4e6f) scl = 3.4e6f;
    if (scl < 50000.0f) scl = 50000.0f;
    return scl / WG_BITS_PER_SAMPLE;
}

WaveGen::DmaPlan WaveGen::_planRate(float frequency_hz) const {
    DmaPlan p;
    p.ok = false; p.N = 2; p.D = 1; p.X = 0; p.Y = 1; p.tickHz = 0; p.actualHz = 0;
    double f = (double)frequency_hz;
    if (!(f > 0.0)) f = 0.0001;
    double cap = (double)_busCapacityHz();
    double tickMax = cap * WG_CAPACITY_MARGIN;
    if (tickMax < 10.0) return p;

    // N: the largest power of two whose sample rate the bus can carry.
    uint32_t N = 2;
    while ((N * 2) <= MAX_WAVEFORM_TABLE_SIZE && f * (double)(N * 2) <= tickMax) N *= 2;
    double tick = f * (double)N;
    if (tick > tickMax) tick = tickMax;   // f above the bus's reach at N = 2: run at capacity, report the truth

    // D and X/Y: the timer must run above its floor; the divider brings the
    // effective tick down. Try a few dividers and keep the closest.
    double clk = (double)clock_get_hz(clk_sys);
    uint32_t D0 = 1;
    if (tick < WG_TICK_T_MIN_HZ) D0 = (uint32_t)ceil(WG_TICK_T_MIN_HZ / tick);
    if (D0 < 1) D0 = 1;
    double bestErr = 1e9;
    for (uint32_t D = D0; D < D0 + 16 && D < (1u << 27); D++) {
        double tt = tick * (double)D;
        if (tt > clk) break;
        double ratio = tt / clk;
        uint16_t X, Y;
        wgBestFraction(ratio, 65535, &X, &Y);
        if (X == 0) continue;
        double act = clk * (double)X / (double)Y / (double)D;
        double err = fabs(act - tick) / tick;
        if (err < bestErr) {
            bestErr = err;
            p.N = N; p.D = D; p.X = X; p.Y = Y;
            p.tickHz = (float)act;
            p.actualHz = (float)(act / (double)N);
            p.ok = true;
        }
        if (bestErr < 1e-9) break;
    }
    return p;
}

void WaveGen::_dmaClaim() {
    if (_dmaAvailable) return;
    _dmaFallbackReason = 0;
#if defined(OG_JUMPERLESS)
    // No OG board attached to verify the stream on an RP2040 (its DMA and
    // I2C blocks would do it); the OG keeps the legacy loop, as with T2.3.
    _dmaFallbackReason = 5;
    return;
#endif
    if (_dac.getWire() != &Wire) { _dmaFallbackReason = 1; return; }   // the image is I2C0's
    if (!_imageAllocated) {
        _image = new (std::nothrow) uint16_t[MAX_WAVEFORM_TABLE_SIZE * 3];
        if (_image == nullptr) { _dmaFallbackReason = 4; return; }
        _imageAllocated = true;
    }
    int a = dma_claim_unused_channel(false);
    int b1 = (a >= 0) ? dma_claim_unused_channel(false) : -1;
    int b2 = (b1 >= 0) ? dma_claim_unused_channel(false) : -1;
    if (a < 0 || b1 < 0 || b2 < 0) {
        if (a >= 0) dma_channel_unclaim((uint)a);
        if (b1 >= 0) dma_channel_unclaim((uint)b1);
        if (b2 >= 0) dma_channel_unclaim((uint)b2);
        _dmaFallbackReason = 2;
        return;
    }
    int t = dma_claim_unused_timer(false);
    if (t < 0) {
        dma_channel_unclaim((uint)a); dma_channel_unclaim((uint)b1); dma_channel_unclaim((uint)b2);
        _dmaFallbackReason = 3;
        return;
    }
    dma_timer_set_fraction((uint)t, 0, 1);   // idle: no ticks
    if (_lockId < 0) {
        int id = spin_lock_claim_unused(false);
        if (id >= 0) { spin_lock_init((uint)id); _lockId = id; }
    }
    _chA = a; _chB1 = b1; _chB2 = b2; _dmaTimer = t;
    _dmaAvailable = true;
}

// Pause the stream at a sample boundary and leave the bus idle: pacing
// timer to 0 (B1 parks; a credit already granted may fire ONE more burst
// within a microsecond, so give it that), then wait for A to be idle and
// the block to have clocked everything out. Bounded; true = idle now.
bool WaveGen::_drainForForeign(uint32_t budgetUs) {
    i2c_hw_t* hw = i2c0_hw;
    dma_timer_set_fraction((uint)_dmaTimer, 0, 1);
    uint32_t t0 = time_us_32();
    while ((time_us_32() - t0) < 3) { tight_loop_contents(); }
    for (;;) {
        bool aIdle = !dma_channel_is_busy((uint)_chA);
        bool busIdle = (hw->status & I2C_IC_STATUS_TFE_BITS) && !(hw->status & I2C_IC_STATUS_MST_ACTIVITY_BITS);
        if (aIdle && busIdle) {
            // once more, a few cycles later, so a burst that started between
            // the two reads is caught
            uint32_t t1 = time_us_32();
            while ((time_us_32() - t1) < 2) { tight_loop_contents(); }
            if (!dma_channel_is_busy((uint)_chA) &&
                (hw->status & I2C_IC_STATUS_TFE_BITS) && !(hw->status & I2C_IC_STATUS_MST_ACTIVITY_BITS)) return true;
        }
        if ((time_us_32() - t0) > budgetUs) return false;
        tight_loop_contents();
    }
}

bool WaveGen::busPause() {
    if (!_dmaStreaming || _lockId < 0) return false;
    spin_lock_t* lk = spin_lock_instance((uint)_lockId);
    uint32_t save = spin_lock_blocking(lk);
    if (!_dmaStreaming || _busPaused) { spin_unlock(lk, save); return false; }
    uint32_t t0 = time_us_32();
    bool idle = _drainForForeign(3000);
    _busPaused = true;
    _busPauseStartUs = time_us_32();
    _busYields++;
    uint32_t dt = time_us_32() - t0;
    if (dt > _busYieldMaxUs) _busYieldMaxUs = dt;
    if (!idle) _wedgeRecoveries++;   // the bus did not drain: the foreign transaction proceeds anyway (Wire has its own timeout)
    spin_unlock(lk, save);
    return true;
}

void WaveGen::busResume() {
    if (_lockId < 0) return;
    spin_lock_t* lk = spin_lock_instance((uint)_lockId);
    uint32_t save = spin_lock_blocking(lk);
    if (_busPaused) {
        _busPaused = false;
        if (_dmaStreaming) {
            // Wire may have left the block's target on the device it talked
            // to; the DAC is ours again.
            i2c_hw_t* hw = i2c0_hw;
            if ((hw->tar & 0x3FF) != _dac.getAddress()) {
                hw->enable = 0;
                hw->tar = _dac.getAddress();
                hw->enable = 1;
            }
            hw->dma_tdlr = 8;
            hw->dma_cr = I2C_IC_DMA_CR_TDMAE_BITS;
            (void)hw->clr_tx_abrt;
            dma_timer_set_fraction((uint)_dmaTimer, _plan.X, _plan.Y);
        }
    }
    spin_unlock(lk, save);
}

